// 🔧 UTILITY FUNCTIONS
export const getSubjectData = (year, subject) => {
  return subjectData[year]?.[subject.toLowerCase()] || null;
};

export const getAllSubjectsForYear = (year) => {
  return subjectData[year] || {};
};

export const getModuleById = (year, subject, moduleId) => {
  const subjectInfo = getSubjectData(year, subject);
  return subjectInfo?.modules.find(module => module.id === moduleId) || null;
};





